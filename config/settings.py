def _lire_reglages(fichier=BASE_DIR / 'reglages.env'):
    """Réglages locaux (« NOM=valeur », une ligne par réglage, # pour un commentaire) sans toucher aux
    variables d'environnement de Windows. Une variable d'environnement déjà définie reste prioritaire."""
    if not fichier.exists():
        return
    for ligne in fichier.read_text(encoding='utf-8-sig').splitlines():
        ligne = ligne.strip()
        if ligne and not ligne.startswith('#') and '=' in ligne:
            nom, valeur = (x.strip() for x in ligne.split('=', 1))
            if nom and valeur:
                os.environ.setdefault(nom, valeur.strip('"').strip("'"))


# Jamais pendant les tests : aucun vrai SMS ne doit partir vers les numéros fictifs des tests.
if not os.environ.get('FINMOB_SANS_REGLAGES') and sys.argv[1:2] != ['test']:
    _lire_reglages()


