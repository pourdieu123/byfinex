def _adresses_locales():
    """Adresses de ce PC sur le réseau local (pour ouvrir l'application depuis un téléphone du même Wi-Fi)."""
    adresses = {'localhost', '127.0.0.1', '[::1]'}
    try:
        adresses.update(socket.gethostbyname_ex(socket.gethostname())[2])
    except OSError:
        pass
    return sorted(adresses)


