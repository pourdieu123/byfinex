def _cle_secrete():
    """Clé secrète : variable DJANGO_SECRET_KEY, sinon clé aléatoire créée une fois et gardée dans .cle_secrete."""
    if os.environ.get('DJANGO_SECRET_KEY'):
        return os.environ['DJANGO_SECRET_KEY']
    fichier = BASE_DIR / '.cle_secrete'
    if not fichier.exists():
        fichier.write_text(secrets.token_urlsafe(64), encoding='utf-8')
        try:
            fichier.chmod(0o600)
        except OSError:
            pass
    return fichier.read_text(encoding='utf-8').strip()


SECRET_KEY = _cle_secrete()

